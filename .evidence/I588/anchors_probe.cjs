const fs = require("fs");
function info(p) {
  const buf = fs.readFileSync(p);
  const s = buf.toString("utf8");
  let bom = 0; for (let i = 0; i < s.length; i++) if (s.charCodeAt(i) === 0xfeff) bom++;
  const crlf = (s.match(/\r\n/g) || []).length;
  const lf = (s.match(/\n/g) || []).length;
  let nonAscii = 0; for (let i = 0; i < s.length; i++) if (s.charCodeAt(i) > 126) nonAscii++;
  return { p, bytes: buf.length, bom, crlf, lf, nonAscii, tail: JSON.stringify(s.slice(-10)) };
}
